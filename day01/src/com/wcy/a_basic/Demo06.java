package com.wcy.a_basic;

public class Demo06 {
    public static void main(String[] args) {
        // 比较运算符
        int a = 250;
        int b = 250;

        System.out.println(a == b);
        System.out.println(a != b);
        System.out.println(a <= b);
        System.out.println(a >= b);
        System.out.println(a > b);
        System.out.println(a < b);
    }
}
